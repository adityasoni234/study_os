export function getRoadmap(id: string): Roadmap | undefined {
  return roadmaps.find((r) => r.id === id)
}

/** Titles for topics that can open a tutor session. */
export const topicTitles: Record<string, string> = {
  'precision-recall': 'Precision & Recall',
  'logistic-regression': 'Logistic Regression',
  'confusion-matrix': 'Confusion Matrix',
  'what-is-rag': 'What is RAG?',
  decorators: 'Decorators & Generators',
  'structured-answers': 'Structured Answers',
  'portfolio-1': 'Portfolio Project #1',
  ask: 'Ask your tutor',
}

export function topicTitle(id: string): string {
  if (topicTitles[id]) return topicTitles[id]
  return id
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ')
}
